// Gloria walking test: enter, walk forward down the aisle with keys, try sitting, take shots.
import { createRequire } from 'node:module';
const require = createRequire('/Users/jurek/Downloads/Claude/Projects/CivicForge/node_modules/');
const { chromium } = require('playwright-core');
const [query, prefix] = process.argv.slice(2);
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist', '--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1100, height: 680 }, deviceScaleFactor: 1 });
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') console.log(m.type() + ':', m.text().slice(0, 300)); });
page.on('pageerror', (e) => console.log('page error:', e.message));
await page.goto('http://localhost:8851/' + query);
await page.waitForFunction(() => window.__gl && window.__gl.ready && __gl.G.state === 'play', null, { timeout: 90000 });
const st = () => page.evaluate(() => { const p = __gl.player; return { pos: [+p.pos.x.toFixed(2), +p.pos.z.toFixed(2)], mode: p.mode, part: __gl.G.part, R: +__gl.G.R.toFixed(2), fps: Math.round(__gl.fps || 0), act: document.getElementById('act').textContent }; });
await page.waitForTimeout(2500);
await page.screenshot({ path: `${prefix}_1.png` });
console.log('start', JSON.stringify(await st()));
await page.keyboard.down('a'); await page.waitForTimeout(500); await page.keyboard.up('a');
await page.keyboard.down('w'); await page.waitForTimeout(2600); await page.keyboard.up('w');
console.log('walked', JSON.stringify(await st()));
await page.screenshot({ path: `${prefix}_2.png` });
await page.keyboard.press('e');
await page.waitForTimeout(1600);
console.log('sit', JSON.stringify(await st()));
await page.screenshot({ path: `${prefix}_3.png` });
await page.keyboard.press('e');
await page.waitForTimeout(1300);
await page.keyboard.down('w'); await page.waitForTimeout(6000); await page.keyboard.up('w');
console.log('altar', JSON.stringify(await st()));
await page.screenshot({ path: `${prefix}_4.png` });
await browser.close();
